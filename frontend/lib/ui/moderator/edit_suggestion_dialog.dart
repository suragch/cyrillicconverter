class EditSuggestionDialog extends StatefulWidget {
  final String initialCyrillic;
  final String initialMenksoft;
  final String? initialExplanation;
  final String? initialComment;
  final String? explicitTargetMenksoft;
  final String? selectedTargetMenksoft;
  final String? submittedBy;
  final String serverUrl;
  final String? authToken;
  final Future<void> Function({
    required String cyrillic,
    required String menksoft,
    String? explanation,
    required bool andApprove,
    String action,
    String? targetMenksoft,
  })
  onSave;

  const EditSuggestionDialog({
    super.key,
    required this.initialCyrillic,
    required this.initialMenksoft,
    this.initialExplanation,
    this.initialComment,
    this.explicitTargetMenksoft,
    this.selectedTargetMenksoft,
    this.submittedBy,
    required this.serverUrl,
    this.authToken,
    required this.onSave,
  });

  static bool isAutoGeneratedEckNote(String? explanation, String? submittedBy) {
    if (submittedBy != 'eck_import' && submittedBy != 'db_discrepancy_review') {
      return false;
    }
    if (explanation == null) {
      return false;
    }
    return explanation.trim().startsWith('ECK ');
  }

  @override
  State<EditSuggestionDialog> createState() => _EditSuggestionDialogState();
}

class _EditSuggestionDialogState extends State<EditSuggestionDialog> {
  late final TextEditingController _cyrillicController;
  late final TextEditingController _latinController;
  late final TextEditingController _explanationController;
  late final FocusNode _latinFocusNode;
  String _previewMenksoft = '';
  bool _showKeyboard = false;
  bool _isSaving = false;
  late final bool _isEckNote;

  Timer? _debounce;
  bool _isCheckingCyrillic = false;
  int _checkRequestId = 0;
  Map<String, dynamic>? _cyrillicCheckResult;
  String _selectedAction = 'add_secondary';
  String? _dialogTargetMenksoft;
  bool _hasInitializedAction = false;

  @override
  void initState() {
    super.initState();
    _isEckNote = EditSuggestionDialog.isAutoGeneratedEckNote(
      widget.initialExplanation,
      widget.submittedBy,
    );
    _cyrillicController = TextEditingController(text: widget.initialCyrillic);
    _latinController = TextEditingController(
      text: LatinIme.menksoftToLatin(widget.initialMenksoft),
    );
    _explanationController = TextEditingController(
      text: _isEckNote ? '' : (widget.initialExplanation ?? ''),
    );
    _previewMenksoft = widget.initialMenksoft;
    _latinFocusNode = FocusNode();
    _latinFocusNode.addListener(_onLatinFocusChanged);

    _latinController.addListener(_onLatinChanged);
    _cyrillicController.addListener(_onCyrillicChanged);

    _checkCyrillicWord(widget.initialCyrillic);
  }

  void _onLatinFocusChanged() {
    setState(() {});
  }

  void _onLatinChanged() {
    final text = _latinController.text;
    if (LatinIme.containsMongolianScript(text)) {
      final converted = LatinIme.convertToLatin(text);
      if (converted != text) {
        _latinController.value = TextEditingValue(
          text: converted,
          selection: TextSelection.collapsed(offset: converted.length),
        );
        return;
      }
    }
    setState(() {
      _previewMenksoft = LatinIme.latinToMenksoft(text);
    });
  }

  void _onCyrillicChanged() {
    final text = _cyrillicController.text.trim();
    _debounce?.cancel();
    _debounce = Timer(const Duration(milliseconds: 350), () {
      if (mounted) {
        _checkCyrillicWord(text);
      }
    });
  }

  Future<void> _checkCyrillicWord(String cyrillic) async {
    final requestId = ++_checkRequestId;
    final clean = cyrillic.trim();
    if (clean.isEmpty) {
      if (mounted) {
        setState(() {
          _cyrillicCheckResult = null;
          _isCheckingCyrillic = false;
          _dialogTargetMenksoft = null;
        });
      }
      return;
    }

    if (mounted) {
      setState(() => _isCheckingCyrillic = true);
    }

    try {
      final headers = {'Content-Type': 'application/json'};
      if (widget.authToken != null) {
        headers['Authorization'] = 'Bearer ${widget.authToken}';
      }

      final res = await http
          .get(
            Uri.parse(
              '${widget.serverUrl}/admin/words/check?cyrillic=${Uri.encodeComponent(clean)}',
            ),
            headers: headers,
          )
          .timeout(const Duration(seconds: 6));

      if (res.statusCode == 200 && mounted && requestId == _checkRequestId) {
        final data = jsonDecode(res.body) as Map<String, dynamic>;
        final defs = (data['definitions'] as List?) ?? [];
        final defMenksofts = defs
            .map((d) => ((d as Map)['menksoft'] as String?)?.trim() ?? '')
            .where((m) => m.isNotEmpty)
            .toList();

        final sameAsInitial =
            LatinIme.normalizeCyrillic(clean) ==
            LatinIme.normalizeCyrillic(widget.initialCyrillic);
        final explicitTarget = sameAsInitial
            ? widget.explicitTargetMenksoft?.trim()
            : null;
        final selectedTarget = sameAsInitial
            ? widget.selectedTargetMenksoft?.trim()
            : null;

        String? nextTarget;
        if (explicitTarget != null &&
            explicitTarget.isNotEmpty &&
            defMenksofts.contains(explicitTarget)) {
          nextTarget = explicitTarget;
        } else if (selectedTarget != null &&
            selectedTarget.isNotEmpty &&
            defMenksofts.contains(selectedTarget)) {
          nextTarget = selectedTarget;
        } else if (defMenksofts.length == 1) {
          nextTarget = defMenksofts.first;
        }

        String nextAction = _selectedAction;
        if (!_hasInitializedAction) {
          _hasInitializedAction = true;
          if (explicitTarget != null && explicitTarget.isNotEmpty) {
            nextAction = 'replace';
          } else {
            nextAction = 'add_secondary';
          }
        } else if (!sameAsInitial) {
          nextAction = 'add_secondary';
        }

        setState(() {
          _cyrillicCheckResult = data;
          _dialogTargetMenksoft = nextTarget;
          _selectedAction = nextAction;
        });
      }
    } catch (_) {
      // Ignore network errors / timeouts
    } finally {
      if (mounted && requestId == _checkRequestId) {
        setState(() => _isCheckingCyrillic = false);
      }
    }
  }

  void _insertKey(String ch) {
    final text = _latinController.text;
    final selection = _latinController.selection;
    int start = selection.start >= 0 ? selection.start : text.length;
    int end = selection.end >= 0 ? selection.end : text.length;

    final newText = text.replaceRange(start, end, ch);
    _latinController.value = TextEditingValue(
      text: newText,
      selection: TextSelection.collapsed(offset: start + ch.length),
    );
  }

  @override
  void dispose() {
    _debounce?.cancel();
    _cyrillicController.dispose();
    _latinController.dispose();
    _explanationController.dispose();
    _latinFocusNode.removeListener(_onLatinFocusChanged);
    _latinFocusNode.dispose();
    super.dispose();
  }

  Future<void> _handleSave({required bool andApprove}) async {
    if (_isSaving) {
      return;
    }
    final cyrillic = _cyrillicController.text.trim();
    if (cyrillic.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('Кирилл үг хоосон байна'),
          backgroundColor: Colors.red,
        ),
      );
      return;
    }

    final cleanPreview = _previewMenksoft.trim();
    if (andApprove && cleanPreview.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('Монгол бичвэр хоосон байхад батлах боломжгүй'),
          backgroundColor: Colors.red,
        ),
      );
      return;
    }

    final exists = _cyrillicCheckResult?['exists'] == true;
    final definitions = (_cyrillicCheckResult?['definitions'] as List?) ?? [];
    final action = exists ? _selectedAction : 'add_primary';
    final targetForReplace = action == 'replace' ? _dialogTargetMenksoft : null;

    if (andApprove &&
        exists &&
        action == 'replace' &&
        definitions.length > 1 &&
        (targetForReplace == null || targetForReplace.isEmpty)) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('Солих бичлэгийг доорх жагсаалтаас сонгоно уу.'),
          backgroundColor: DesktopTheme.warning,
        ),
      );
      return;
    }

    // Check if homonym without note when adding a different spelling
    final note = _explanationController.text.trim();
    final alreadyIdentical = definitions.any(
      (d) => ((d as Map)['menksoft'] as String?)?.trim() == cleanPreview,
    );

    if (andApprove &&
        exists &&
        action != 'replace' &&
        !alreadyIdentical &&
        note.isEmpty &&
        cleanPreview.isNotEmpty) {
      final proceed = await showDialog<bool>(
        context: context,
        builder: (ctx) => DesktopDialogFrame(
          title: 'Ялгах тэмдэглэл шаардлагатай',
          maxWidth: 440,
          leadingIcon: const Icon(
            Icons.warning_amber_rounded,
            size: 18,
            color: DesktopTheme.warning,
          ),
          content: Text(
            '"$cyrillic" кирилл үг толь бичигт аль хэдийн бүртгэгдсэн байна. '
            'Энэ нь олон утгатай үг (homonym) болох тул ялгах тайлбар/тэмдэглэл бичих шаардлагатай.\n\n'
            'Тэмдэглэлгүйгээр үргэлжлүүлэх үү?',
            style: DesktopTheme.body,
          ),
          actions: [
            DesktopButton(
              onPressed: () => Navigator.pop(ctx, false),
              label: 'Тэмдэглэл бичих',
              variant: DesktopButtonVariant.secondary,
              isDense: true,
            ),
            const SizedBox(width: 8),
            DesktopButton(
              onPressed: () => Navigator.pop(ctx, true),
              label: 'Тэмдэглэлгүй үргэлжлүүлэх',
              variant: DesktopButtonVariant.primary,
              isDense: true,
            ),
          ],
        ),
      );
      if (proceed != true) {
        return;
      }
    }

    setState(() => _isSaving = true);
    try {
      await widget.onSave(
        cyrillic: cyrillic,
        menksoft: cleanPreview,
        explanation: note,
        andApprove: andApprove,
        action: action,
        targetMenksoft: targetForReplace,
      );
      if (mounted) {
        Navigator.pop(context, true);
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Алдаа гарлаа: $e'),
            backgroundColor: Colors.red,
          ),
        );
      }
    } finally {
      if (mounted) {
        setState(() => _isSaving = false);
      }
    }
  }

